alter table public.platform_users enable row level security;

create or replace function public.is_platform_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.platform_users pu
    where pu.active is true
      and pu.role = 'owner'
      and lower(pu.email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.is_platform_owner() from public;
grant execute on function public.is_platform_owner() to authenticated;

revoke all on public.platform_users from anon;
grant select, insert, update, delete on public.platform_users to authenticated;
grant usage, select on sequence public.platform_users_id_seq to authenticated;

drop policy if exists "platform users read own or owner" on public.platform_users;
create policy "platform users read own or owner"
on public.platform_users
for select
to authenticated
using (
  lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  or public.is_platform_owner()
);

drop policy if exists "platform owner inserts users" on public.platform_users;
create policy "platform owner inserts users"
on public.platform_users
for insert
to authenticated
with check (public.is_platform_owner());

drop policy if exists "platform owner updates users" on public.platform_users;
create policy "platform owner updates users"
on public.platform_users
for update
to authenticated
using (public.is_platform_owner())
with check (public.is_platform_owner());

drop policy if exists "platform owner deletes users" on public.platform_users;
create policy "platform owner deletes users"
on public.platform_users
for delete
to authenticated
using (public.is_platform_owner());

commit;
